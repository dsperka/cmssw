#!/bin/bash
# Full MTD timing validation: legacy TrackExtenderWithMTD vs the Alpaka MTD timing module.
# Run inside cmsenv from an empty work directory:
#
#   run_validation.sh [maxEvents] [threads] [fileList] [filePrefix]
#
#   maxEvents   default 1000
#   threads     per job, default 8 (the two reconstruction jobs run in parallel, ~9 GB each at PU200)
#   fileList    GEN-SIM-RECO LFNs, default relvalTTbar_PU200_D128_20_1_0_pre3.txt (10 x 100 events)
#   filePrefix  prepended to each LFN, default root://cms-xrd-global.cern.ch/ (use file:/path/to/store/.. for local copies)
# Optional: MTD_NOTE="html text" adds a note under the summary tables.
#           NEW_OPTS="vertices=alpaka" extra options of the alpaka job (3D vertices and tofPID4DnoPID on the device)
#           NEW_NAME="..." name of the alpaka job in the galleries
#
# Output: DQMIO files, harvested DQM_V0001_R000000001__MTD__{legacy,alpaka}__VALID.root,
#         summary.{json,html}, mtd_{Vertices,Tracks}_gallery.html, dqm_plots/ (overlays + summary.csv)
set -e
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
NEV=${1:-1000}
THREADS=${2:-8}
LIST=${3:-$HERE/relvalTTbar_PU200_D128_20_1_0_pre3.txt}
PREFIX=${4:-root://cms-xrd-global.cern.ch/}
FILES=$(sed "s|^|${PREFIX}|" "$LIST" | paste -sd, -)

NEW_NAME=${NEW_NAME:-Alpaka MTD timing (no refit)}
for t in legacy alpaka; do
  extra=""
  [ $t = alpaka ] && extra="$NEW_OPTS"
  cmsRun "$HERE/mtdValidation_cfg.py" timing=$t $extra maxEvents=$NEV threads=$THREADS inputFiles="$FILES" \
    output=mtdValidation_${t}_DQMIO.root > reco_$t.log 2>&1 &
done
wait
for t in legacy alpaka; do
  cmsRun "$HERE/mtdHarvest_cfg.py" inputFiles=file:mtdValidation_${t}_DQMIO.root label=$t > harvest_$t.log 2>&1
done

L=DQM_V0001_R000000001__MTD__legacy__VALID.root
N=DQM_V0001_R000000001__MTD__alpaka__VALID.root
python3 "$HERE/mtd_summary.py" --ref $L --new $N --new-name "$NEW_NAME" --events "$NEV events" ${MTD_NOTE:+--note "$MTD_NOTE"} \
  --json summary.json --html summary.html
for sec in Vertices Tracks; do
  python3 "$HERE/render_dqm_gallery.py" --old $L --inblocks $N --base-dir "DQMData/Run 1/MTD/Run summary/$sec" \
    --display "Old=Legacy TrackExtenderWithMTD (refit)" --display "InBlocks=$NEW_NAME" \
    --summary-html summary.html --eyebrow "RecoMTD / TrackExtenderAlpaka &middot; MTD validation" \
    --footer "RecoMTD/TrackExtenderAlpaka &middot; generated by render_dqm_gallery.py" \
    --title "MTD $sec validation: legacy vs $NEW_NAME" --subtitle "$NEV events" \
    --out mtd_${sec}_gallery.html --workdir work_$sec > render_$sec.log 2>&1
done
python3 "$HERE/overlay_dqm.py" $L $N dqm_plots > overlay.log 2>&1
echo "done: mtd_Vertices_gallery.html mtd_Tracks_gallery.html dqm_plots/"
